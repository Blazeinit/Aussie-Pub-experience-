// "how do I find the new machines": the route, step by step, on an iPhone-sized screen, from the published file
import { launch, done } from './harness.mjs';
import fs from 'fs';
const g = await launch({ quality: 'high', port: 8191, w: 844, h: 390, mobile: true, file: 'Last-Drinks-offline.html' });
const { page } = g; const boxes = {};
const box = async (name, sel) => { boxes[name] = await page.evaluate(s => { const e = document.querySelector(s); if (!e) return null; const r = e.getBoundingClientRect(); return [r.left, r.top, r.width, r.height]; }, sel); };
await box('01', '#btnNew'); await g.shot('howto', '01_title');
await page.click('#btnNew'); await page.waitForTimeout(400); await box('02', '.dcard[data-diff=normal]'); await g.shot('howto', '02_who');
await page.click('.dcard[data-diff=normal]'); await page.waitForTimeout(500);
await page.evaluate(() => document.querySelector('.vchip[data-v=rsl]').scrollIntoView({ block: 'center' })); await page.waitForTimeout(300);
await box('03', '.vchip[data-v=rsl]'); await g.shot('howto', '03_daycard_rsl');
await page.click('.vchip[data-v=rsl]'); await page.waitForTimeout(350); await g.shot('howto', '04_cab');
await page.waitForFunction(() => window.__ready && document.querySelector('#dayCard') && !document.querySelector('#dayCard').classList.contains('hidden'), null, { timeout: 240000 });
await page.waitForTimeout(600);
await page.evaluate(() => { const b = document.getElementById('btnGo'); b && b.scrollIntoView({ block: 'center' }); }); await page.waitForTimeout(300);
await box('05', '#btnGo'); await g.shot('howto', '05_daycard_go');
await page.click('#btnGo'); await page.waitForTimeout(800); await g.ev('window.__sim(2)');
await g.ev(`document.getElementById('fade').style.transition='none'; document.getElementById('fade').style.opacity=0;`);
await g.ev(`(()=>{ const G=window.__game; G.Game.closePanel(); window.__sim(0.5); })()`);
console.log('venue now', await g.ev('window.__game.VENUE.id'));
await g.at(0, 9.5, 0, 0.16, 1.2); await g.shot('howto', '06_outside');
await g.ev(`(()=>{ const G=window.__game; G.Game.entered=true; G.Game.askedHome=true; })()`);
await g.at(-0.4, -1.0, -0.32, 0.02, 1.2); await g.shot('howto', '07_inside');
await g.at(0.6, -10, -Math.PI / 2, 0.06, 1.2); await g.shot('howto', '08_gaming_door');
await g.at(4.4, -9.6, -0.42, 0.1, 1.2); await g.shot('howto', '09_gaming_room');
await g.at(8, -12.8, 0, 0.14, 1.2); await g.shot('howto', '10_bank_left');
await g.at(10.6, -12.8, 0.25, 0.14, 1.2); await g.shot('howto', '11_bank_right');
await g.at(7.5, -8.4, Math.PI, 0.1, 1.2); await g.shot('howto', '12_turn_around');
fs.writeFileSync('out/howto/boxes.json', JSON.stringify(boxes));
console.log('errors', g.errs.filter(e => !/Failed to load resource|BiquadFilter|Canvas2D|CORS|file:\/\//.test(e)).join('\n'));
await g.close(); done();
